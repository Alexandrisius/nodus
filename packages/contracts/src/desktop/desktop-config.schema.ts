import { z } from 'zod';

/**
 * Ответ публичного эндпоинта `GET /api/v1/desktop/config` — контракт десктоп-
 * оболочки с сервером портала (ADR-0019). Публичный (без авторизации):
 * оболочка спрашивает его ДО входа пользователя, на экране подключения.
 */
export const desktopConfigSchema = z.object({
  /** Идентификация сервера на экране подключения/смены сервера (модель Битрикса). */
  serverName: z.string().min(1).max(120),
  /**
   * Минимальная поддерживаемая версия оболочки (semver). Оболочка старше
   * минимума показывает экран «обновите приложение» и не пускает к порталу —
   * страховка от тихих поломок контрактов моста. `0.0.0` — ограничения нет.
   */
  minShellVersion: z.string().regex(/^\d+\.\d+\.\d+/, 'semver major.minor.patch'),
});

export type DesktopConfig = z.infer<typeof desktopConfigSchema>;
