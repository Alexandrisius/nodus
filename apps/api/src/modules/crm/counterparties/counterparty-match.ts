/**
 * Нормализация названия для подсказки похожих контрагентов (#460).
 *
 * Это техническая нормализация СРАВНЕНИЯ, а не бизнес-справочник (I15):
 * организационно-правовые формы не классифицируются и не хранятся — они лишь
 * отбрасываются при нечётком сравнении, чтобы «ООО «СтройЗаказчик»» и
 * «СтройЗаказчик» совпадали. Значения не редактируются и в БД не меняются.
 */

/** Организационно-правовые формы (и их сокращения) — шум для сравнения названий. */
const LEGAL_FORM_TOKENS = new Set([
  'ооо',
  'оао',
  'зао',
  'пао',
  'ао',
  'одо',
  'ип',
  'чп',
  'уп',
  'чуп',
  'руп',
  'куп',
  'чтуп',
  'сооо',
  'иооо',
]);

/** Минимальная длина названия, при которой подсказка по имени вообще работает. */
export const MIN_SIMILAR_NAME_LENGTH = 3;

/** Порог нечёткого сходства (`word_similarity`); подобран тестами подсказки. */
export const SIMILAR_NAME_THRESHOLD = 0.45;

/** Максимум совпадений в подсказке (прецедент `GET /tasks/stages`). */
export const SIMILAR_LIMIT = 5;

/**
 * Приводит название к сравнению: нижний регистр, `ё→е`, всё несловесное
 * (кавычки, точки, дефисы) — в пробел, токены орг-форм выброшены.
 * `АО «Галургия»` → `галургия`; `ООО "Строй-Заказчик"` → `строй заказчик`.
 */
export function normalizeCounterpartyName(raw: string): string {
  return raw
    .toLowerCase()
    .replace(/ё/gu, 'е')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .trim()
    .split(' ')
    .filter((token) => token !== '' && !LEGAL_FORM_TOKENS.has(token))
    .join(' ');
}

/**
 * Строка для SQL-подсказки: нормализованное название или `''`, если после
 * нормализации осталось меньше 3 символов (по имени не ищем — шум).
 */
export function similarNameQuery(raw: string | undefined): string {
  if (!raw) return '';
  const normalized = normalizeCounterpartyName(raw);
  return normalized.length >= MIN_SIMILAR_NAME_LENGTH ? normalized : '';
}
