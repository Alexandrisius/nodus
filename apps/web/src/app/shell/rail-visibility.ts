import { useRouterState } from '@tanstack/react-router';

/**
 * Служебная полоса СКРЫТА на модуле мессенджер (`/chat*`): она дублировала бы
 * список бесед самого модуля; мягкая рама расширяется до правого края
 * периметра (вердикт владельца 15.09.2026, модель Битрикс24, план
 * `docs/mvp/messenger-fullscreen-plan.md`).
 *
 * Под ПОЛНОЭКРАННОЙ карточкой мессенджера полоса НЕ скрывается: карточка
 * (inset-2 периметра) накрывает её целиком — дубль невидим и недоступен
 * (click-catcher карточки поверх), зато карточки стека ПОД ней не меняют
 * геометрию: без этого их правый край ехал на 40px во время раскрытия
 * карточки мессенджера, и лишняя ширина уходила в левую зону сетки задачи —
 * «непрофессиональное» движение границы (баг-вердикт владельца 15.09.2026).
 *
 * Состояние полосы (`edgeOpen`, nodus-shell-v1) НЕ сбрасывается: вне `/chat*`
 * полоса возвращается в прежнем режиме.
 *
 * Потребители: RightRail (колонка w→0), SliderPanel (stripW=0 — правый край
 * карточки = край периметра; фулскрин-карточка мессенджера получает stripW=0
 * своим пропом `fullscreen`, а не этим правилом).
 */
export function useRailHidden(): boolean {
  const pathname = useRouterState({ select: (s) => s.location.pathname });
  return pathname.startsWith('/chat');
}
