/** Id-хелперы демо-писем (#55): вынесены отдельно, чтобы наборы писем,
 *  бесед чата писем и задач-поручений (цепочка «Письмо → Задача») не
 *  образовывали цикл импортов. */

/** Письмо: lid(1…10) — зарегистрированные Вх-2026/108…117, lid(21…26) — «Новые». */
export const lid = (n: number): string => `80000000-0000-4000-8000-${String(n).padStart(12, '0')}`;

/** Вложение письма (строка `letter_attachments`). */
export const laid = (n: number): string => `81000000-0000-4000-8000-${String(n).padStart(12, '0')}`;

/** Файл модуля files под вложением. */
export const lfid = (n: number): string => `82000000-0000-4000-8000-${String(n).padStart(12, '0')}`;
