/**
 * Поверхность сообщения — ЕДИНАЯ точка решения «чем залито сообщение» во ВСЕХ
 * хостах мессенджера (#127, вердикт владельца 28.09.2026).
 *
 * Сообщение в Nodus — одна сущность с НЕСКОЛЬКИМИ хостами рендера: пузырь чата
 * и корень треда (`chat-message.tsx` — Bubble-примитив, варианты default/card),
 * карточка поста канала (`thread-feed.tsx` — карточка поверх ленты), обсуждение
 * задачи (`task-discussion.tsx` — тот же ChatMessageItem). До #127 заливку
 * каждый хост решал сам (пузырь — глобальные --primary/--card, пост —
 * node-panel): правка палитры теряла хосты, и посты оказывались «пузырями
 * другого цвета» (вердикт 28.09.2026: «не можем сделать их другого цвета»).
 * Поэтому: поверхность и её акцент берутся ТОЛЬКО здесь; варианты default/card
 * Bubble-примитива — те же токены bubble-* (packages/ui bubble.tsx). Новый хост
 * рендера сообщения НЕ изобретает свою заливку — берёт отсюда.
 *
 * Палитра — канон Telegram (токены bubble-in/bubble-out обеих тем,
 * globals.css): чужое сообщение — светлая поверхность, своё — залитая;
 * акцентные элементы на залитой (мета, галочки, цитата, чипы, ссылка треда) —
 * bubble-out-accent, на светлой — info.
 */
export function messageSurface(mine: boolean) {
  return {
    /** Сообщение на залитой (своей) поверхности — для Meta/Reactions/ReplyHeader. */
    onFilled: mine,
    /** Тон поверхности для селекторов тинта выделения (глоб. CSS #132 р.5):
     'out' — bubble-out (своё), 'in' — bubble-in (чужое); той же формулой
     красятся пузырь и хвост — стык бесшовен. */
    tone: (mine ? 'out' : 'in') as 'out' | 'in',
    /** Заливка + текст поверхности: своё — bubble-out, чужое — bubble-in. */
    fill: mine
      ? 'bg-bubble-out text-bubble-out-foreground'
      : 'bg-bubble-in text-bubble-in-foreground',
    /** Текст-ссылка на поверхности («Обсудить»): foreground поверхности с
        weight/стрелкой как affordance — info на тонированной полосе не
        дотягивал WCAG AA в обеих темах (валидатор #127); hue «нового» несёт
        точка accentBg (графический контраст). */
    linkText: mine ? 'text-bubble-out-foreground' : 'text-bubble-in-foreground/80',
    /** Вторичный текст на поверхности (счётчик ответов ленты): foreground
        поверхности (на залитой — целиком, на светлой — /70): muted-foreground
        на залитой тёмной проваливался до ~1.9:1 (регресс #127, валидатор). */
    stripText: mine ? 'text-bubble-out-foreground' : 'text-bubble-in-foreground/70',
    /** Акцентная точка/глиф на поверхности (индикатор непрочитанных ответов). */
    accentBg: mine ? 'bg-bubble-out-accent' : 'bg-info',
    /** Кольцо-разделитель на поверхности (стопка аватаров участников треда). */
    ring: mine ? 'ring-bubble-out' : 'ring-bubble-in',
  };
}
